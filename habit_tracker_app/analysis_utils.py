# RESUMEN ESTADÍSTICO MEJORADO
# =============================================================================

def resumen_avanzado(df: pd.DataFrame) -> pd.DataFrame:
    """
    Genera un resumen estadístico más completo que df.describe().

    Args:
        df: DataFrame con datos de hábitos

    Returns:
        DataFrame con estadísticas descriptivas mejoradas
    """
    df_numerico = df.select_dtypes(include=[np.number])

    if df_numerico.empty:
        return pd.DataFrame()

    resumen = pd.DataFrame({
        'Media': df_numerico.mean(),
        'Mediana': df_numerico.median(),
        'Desv_Std': df_numerico.std(),
        'Mínimo': df_numerico.min(),
        'Máximo': df_numerico.max(),
        'Rango': df_numerico.max() - df_numerico.min(),
        'CV_%': (df_numerico.std() / df_numerico.mean() * 100).round(1),  # Coeficiente de variación
        'Datos_Completos_%': ((df_numerico.count() / len(df_numerico)) * 100).round(1)
    }).round(2)

    return resumen


def resumen_basico(df: pd.DataFrame) -> pd.DataFrame:
    """
    Función legacy compatible con tu código anterior.
    """
    return df.describe().round(2)


