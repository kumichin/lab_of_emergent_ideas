# =============================================================================

def analizar_correlaciones(
    df: pd.DataFrame,
    umbral_correlacion: float = 0.5
) -> List[Tuple[str, str, float]]:
    """
    Encuentra correlaciones significativas entre hábitos.

    Args:
        df: DataFrame con datos de hábitos
        umbral_correlacion: Valor mínimo de correlación para reportar

    Returns:
        Lista de tuplas (habito1, habito2, correlacion)
    """
    # Seleccionar solo columnas numéricas
    df_numerico = df.select_dtypes(include=[np.number])

    if len(df_numerico.columns) < 2:
        return []

    # Calcular matriz de correlación
    corr_matrix = df_numerico.corr()

    # Encontrar correlaciones significativas
    correlaciones = []
    for i in range(len(corr_matrix.columns)):
        for j in range(i + 1, len(corr_matrix.columns)):
            corr_valor = corr_matrix.iloc[i, j]

            if abs(corr_valor) >= umbral_correlacion:
                habito1 = corr_matrix.columns[i]
                habito2 = corr_matrix.columns[j]
                correlaciones.append((habito1, habito2, corr_valor))

    # Ordenar por magnitud de correlación
    correlaciones.sort(key=lambda x: abs(x[2]), reverse=True)

    return correlaciones


