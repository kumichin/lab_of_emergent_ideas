def detectar_anomalias(serie: pd.Series, umbral_zscore: float = 2.5) -> List[Tuple[int, float]]:
    """
    Detecta valores atípicos usando Z-score.

    Args:
        serie: Serie de pandas con valores numéricos
        umbral_zscore: Número de desviaciones estándar para considerar anomalía

    Returns:
        Lista de tuplas (índice, valor) de los valores anómalos
    """
    serie_limpia = serie.dropna()

    if len(serie_limpia) < 5:
        return []

    # Calcular Z-scores
    media = serie_limpia.mean()
    std = serie_limpia.std()

    if std == 0:
        return []

    z_scores = np.abs((serie_limpia - media) / std)

    # Detectar anomalías
    anomalias = []
    for idx, z_score in zip(serie_limpia.index, z_scores):
        if z_score > umbral_zscore:
            anomalias.append((idx, serie[idx]))

    return anomalias


