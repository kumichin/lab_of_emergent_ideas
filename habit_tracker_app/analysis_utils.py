@dataclass
class Alerta:
    """Estructura para almacenar alertas con metadata"""
    severidad: SeveridadAlerta
    titulo: str
    mensaje: str
    metrica: float
    umbral: Optional[float] = None
    tendencia: Optional[str] = None


def generar_alertas_inteligentes(
    df: pd.DataFrame,
    umbrales_personalizados: Optional[Dict[str, UmbralHabito]] = None,
    incluir_tendencias: bool = True,
    incluir_anomalias: bool = True
) -> List[Alerta]:
    """
    Genera alertas inteligentes basadas en análisis de hábitos.

    Args:
        df: DataFrame con datos de hábitos (debe tener columna de fecha)
        umbrales_personalizados: Diccionario con umbrales custom (opcional)
        incluir_tendencias: Si True, analiza tendencias temporales
        incluir_anomalias: Si True, detecta días atípicos

    Returns:
        Lista de alertas ordenadas por severidad
    """
    alertas = []
    umbrales = umbrales_personalizados or UMBRALES_DEFAULT

    # Analizar cada columna numérica
    for columna in df.select_dtypes(include=[np.number]).columns:
        umbral = _detectar_habito(columna)

        if umbral is None:
            continue  # No es un hábito conocido

        serie = df[columna]
        media = serie.mean()

        # ========== ANÁLISIS DE PROMEDIOS ==========

        # Verificar mínimo saludable
        if umbral.minimo_saludable and media < umbral.minimo_saludable:
            severidad = SeveridadAlerta.CRITICO if media < umbral.minimo_saludable * 0.8 else SeveridadAlerta.ADVERTENCIA
            alertas.append(Alerta(
                severidad=severidad,
                titulo=f"{umbral.nombre} insuficiente",
                mensaje=f"Tu promedio es {media:.1f} {umbral.unidad}, pero se recomienda al menos {umbral.minimo_saludable} {umbral.unidad}.",
                metrica=media,
                umbral=umbral.minimo_saludable
            ))

        # Verificar máximo saludable
        if umbral.maximo_saludable and media > umbral.maximo_saludable:
            severidad = SeveridadAlerta.CRITICO if media > umbral.maximo_saludable * 1.2 else SeveridadAlerta.ADVERTENCIA
            alertas.append(Alerta(
                severidad=severidad,
                titulo=f"{umbral.nombre} excesivo",
                mensaje=f"Tu promedio es {media:.1f} {umbral.unidad}, pero se recomienda máximo {umbral.maximo_saludable} {umbral.unidad}.",
                metrica=media,
                umbral=umbral.maximo_saludable
            ))

        # Verificar si está en rango óptimo
        if umbral.optimo:
            diferencia = abs(media - umbral.optimo)
            if diferencia < umbral.optimo * 0.1:  # Dentro del 10% del óptimo
                alertas.append(Alerta(
                    severidad=SeveridadAlerta.POSITIVO,
                    titulo=f"¡Excelente {umbral.nombre}!",
                    mensaje=f"Tu promedio de {media:.1f} {umbral.unidad} está muy cerca del óptimo ({umbral.optimo} {umbral.unidad}).",
                    metrica=media,
                    umbral=umbral.optimo
                ))

        # ========== ANÁLISIS DE TENDENCIAS ==========

        if incluir_tendencias and len(serie) >= 7:
            tendencia, pendiente = calcular_tendencia(serie)

            # Alertas de tendencias preocupantes
            if tendencia == 'bajando' and umbral.minimo_saludable:
                if media < umbral.minimo_saludable * 1.2:  # Cerca del límite y bajando
                    alertas.append(Alerta(
                        severidad=SeveridadAlerta.ADVERTENCIA,
                        titulo=f"Tendencia decreciente en {umbral.nombre}",
                        mensaje=f"Tu {umbral.nombre} está disminuyendo. Promedio actual: {media:.1f} {umbral.unidad}.",
                        metrica=media,
                        tendencia='bajando'
                    ))

            elif tendencia == 'subiendo' and umbral.maximo_saludable:
                if media > umbral.maximo_saludable * 0.8:  # Cerca del límite y subiendo
                    alertas.append(Alerta(
                        severidad=SeveridadAlerta.ADVERTENCIA,
                        titulo=f"Tendencia creciente en {umbral.nombre}",
                        mensaje=f"Tu {umbral.nombre} está aumentando. Promedio actual: {media:.1f} {umbral.unidad}.",
                        metrica=media,
                        tendencia='subiendo'
                    ))

            # Alertas de mejoras
            elif tendencia == 'subiendo' and umbral.minimo_saludable:
                if media > umbral.minimo_saludable:
                    alertas.append(Alerta(
                        severidad=SeveridadAlerta.POSITIVO,
                        titulo=f"¡Mejorando en {umbral.nombre}!",
                        mensaje=f"Tu {umbral.nombre} está aumentando consistentemente. ¡Sigue así!",
                        metrica=media,
                        tendencia='subiendo'
                    ))

        # ========== DETECCIÓN DE ANOMALÍAS ==========

        if incluir_anomalias:
            anomalias = detectar_anomalias(serie)

            if len(anomalias) > 0:
                # Solo alertar si hay más de 2 anomalías
                if len(anomalias) > 2:
                    alertas.append(Alerta(
                        severidad=SeveridadAlerta.INFO,
                        titulo=f"Días atípicos en {umbral.nombre}",
                        mensaje=f"Se detectaron {len(anomalias)} días con valores inusuales en {umbral.nombre}.",
                        metrica=len(anomalias)
                    ))

    # Ordenar por severidad (Crítico > Advertencia > Info > Positivo)
    orden_severidad = {
        SeveridadAlerta.CRITICO: 0,
        SeveridadAlerta.ADVERTENCIA: 1,
        SeveridadAlerta.INFO: 2,
        SeveridadAlerta.POSITIVO: 3
    }

    alertas_ordenadas = sorted(alertas, key=lambda x: orden_severidad[x.severidad])

    return alertas_ordenadas


def generar_alertas(df: pd.DataFrame) -> List[str]:
    """
    Función simplificada compatible con tu código anterior.
    Mantiene la misma interfaz pero usa el motor mejorado internamente.

    Args:
        df: DataFrame con datos de hábitos

    Returns:
        Lista de strings con mensajes de alerta
    """
    alertas_obj = generar_alertas_inteligentes(df)

    # Convertir objetos Alerta a strings simples
    mensajes = []
    for alerta in alertas_obj:
        mensaje = f"{alerta.severidad.value} {alerta.titulo}: {alerta.mensaje}"
        mensajes.append(mensaje)

    return mensajes


