def _detectar_habito(nombre_columna: str) -> Optional[UmbralHabito]:
    """
    Detecta automáticamente qué tipo de hábito es una columna.

    Args:
        nombre_columna: Nombre de la columna del DataFrame

    Returns:
        UmbralHabito si se detecta, None si no se reconoce
    """
    nombre_lower = nombre_columna.lower()

    # Buscar coincidencias en los umbrales definidos
    for clave, umbral in UMBRALES_DEFAULT.items():
        if clave in nombre_lower:
            return umbral

    return None


