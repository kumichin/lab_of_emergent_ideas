# =============================================================================

def calcular_tendencia(serie: pd.Series) -> Tuple[str, float]:
    """
    Calcula la tendencia de una serie temporal usando regresión lineal simple.

    Args:
        serie: Serie de pandas con valores numéricos

    Returns:
        Tupla con (dirección, pendiente) donde dirección es 'subiendo', 'bajando' o 'estable'
    """
    # Eliminar NaN y verificar que hay suficientes datos
    serie_limpia = serie.dropna()

    if len(serie_limpia) < 3:
        return 'insuficiente', 0.0

    # Crear índices numéricos para la regresión
    x = np.arange(len(serie_limpia))
    y = serie_limpia.values

    # Calcular pendiente usando mínimos cuadrados
    pendiente = np.polyfit(x, y, 1)[0]

    # Clasificar la tendencia
    if abs(pendiente) < 0.1:  # Cambio menor al 10% del rango
        direccion = 'estable'
    elif pendiente > 0:
        direccion = 'subiendo'
    else:
        direccion = 'bajando'

    return direccion, pendiente


