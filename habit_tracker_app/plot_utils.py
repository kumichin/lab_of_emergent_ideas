# GRÁFICO 1: TENDENCIAS TEMPORALES
# =============================================================================

def grafico_tendencias(df: pd.DataFrame, columnas: Optional[List[str]] = None) -> go.Figure:
    """
    Genera un gráfico de líneas con las tendencias temporales de los hábitos.

    Args:
        df: DataFrame con datos de hábitos
        columnas: Lista de columnas a graficar. Si None, usa todas las numéricas

    Returns:
        Figura de Plotly con las tendencias
    """
    col_fecha = _detectar_columna_fecha(df)

    if col_fecha is None:
        raise ValueError("No se encontró una columna de fecha en el DataFrame")

    # Si no se especifican columnas, usar todas las numéricas
    if columnas is None:
        columnas = df.select_dtypes(include=[np.number]).columns.tolist()

    # Crear figura con subplots
    fig = make_subplots(
        rows=len(columnas),
        cols=1,
        subplot_titles=[col.replace('_', ' ').title() for col in columnas],
        vertical_spacing=0.05
    )

    # Añadir una línea por cada hábito
    for i, col in enumerate(columnas, 1):
        tipo = _detectar_tipo_habito(col)

        if tipo == 'positivo':
            color = COLORES_POSITIVOS[0]
        elif tipo == 'negativo':
            color = COLORES_NEGATIVOS[0]
        else:
            color = COLORES_NEUTROS[0]

        fig.add_trace(
            go.Scatter(
                x=df[col_fecha],
                y=df[col],
                mode='lines+markers',
                name=col.replace('_', ' ').title(),
                line=dict(color=color, width=2),
                marker=dict(size=6),
                hovertemplate='<b>%{x|%d/%m/%Y}</b><br>Valor: %{y:.1f}<extra></extra>'
            ),
            row=i, col=1
        )

        # Añadir línea de promedio
        promedio = df[col].mean()
        fig.add_hline(
            y=promedio,
            line_dash="dash",
            line_color="gray",
            opacity=0.5,
            row=i, col=1
        )

    fig.update_layout(
        height=300 * len(columnas),
        title_text="📈 Evolución de Hábitos en el Tiempo",
        showlegend=False,
        template=TEMPLATE,
        hovermode='x unified'
    )

    fig.update_xaxes(title_text="Fecha")
    fig.update_yaxes(title_text="Valor")

    return fig


