# GRÁFICO 4: COMPARATIVA SEMANAL/MENSUAL
# =============================================================================

def grafico_comparativa_temporal(
    df: pd.DataFrame,
    columna: str,
    frecuencia: str = 'W'
) -> go.Figure:
    """
    Compara promedios por semana o mes.

    Args:
        df: DataFrame con datos de hábitos
        columna: Columna a analizar
        frecuencia: 'W' para semanal, 'M' para mensual

    Returns:
        Figura de Plotly con la comparativa
    """
    col_fecha = _detectar_columna_fecha(df)

    if col_fecha is None:
        raise ValueError("No se encontró una columna de fecha")

    # Agrupar por período
    df_temp = df.copy()
    df_temp[col_fecha] = pd.to_datetime(df_temp[col_fecha])
    df_temp = df_temp.set_index(col_fecha)

    if frecuencia == 'W':
        agrupado = df_temp[columna].resample('W').mean()
        titulo_periodo = "Semana"
    else:
        agrupado = df_temp[columna].resample('M').mean()
        titulo_periodo = "Mes"

    tipo = _detectar_tipo_habito(columna)
    color = COLORES_POSITIVOS[0] if tipo == 'positivo' else COLORES_NEUTROS[0]

    fig = go.Figure()

    # Barras
    fig.add_trace(go.Bar(
        x=agrupado.index,
        y=agrupado.values,
        marker_color=color,
        name=columna,
        hovertemplate='<b>%{x|%d/%m/%Y}</b><br>Promedio: %{y:.1f}<extra></extra>'
    ))

    # Línea de tendencia
    fig.add_trace(go.Scatter(
        x=agrupado.index,
        y=agrupado.values,
        mode='lines',
        line=dict(color='red', width=2, dash='dash'),
        name='Tendencia',
        hoverinfo='skip'
    ))

    fig.update_layout(
        title=f"📅 Promedio {titulo_periodo.lower()}al de {columna.replace('_', ' ').title()}",
        xaxis_title=titulo_periodo,
        yaxis_title="Promedio",
        template=TEMPLATE,
        height=400,
        showlegend=True
    )

    return fig


