# FUNCIÓN PARA GENERAR DASHBOARD COMPLETO
# =============================================================================

def generar_dashboard_completo(df: pd.DataFrame, guardar_html: bool = False) -> List[go.Figure]:
    """
    Genera todas las visualizaciones automáticamente.

    Args:
        df: DataFrame con datos de hábitos
        guardar_html: Si True, guarda cada gráfico como HTML

    Returns:
        Lista con todas las figuras generadas
    """
    figuras = []
    columnas_numericas = df.select_dtypes(include=[np.number]).columns.tolist()

    print("🎨 Generando visualizaciones...")

    try:
        # 1. Tendencias temporales
        print("   📈 Gráfico de tendencias...")
        fig1 = grafico_tendencias(df)
        figuras.append(fig1)
        if guardar_html:
            fig1.write_html("tendencias.html")
    except Exception as e:
        print(f"   ⚠️ No se pudo generar tendencias: {e}")

    try:
        # 2. Distribuciones
        print("   📊 Gráfico de distribuciones...")
        fig2 = grafico_distribuciones(df)
        figuras.append(fig2)
        if guardar_html:
            fig2.write_html("distribuciones.html")
    except Exception as e:
        print(f"   ⚠️ No se pudo generar distribuciones: {e}")

    try:
        # 3. Correlaciones
        if len(columnas_numericas) >= 2:
            print("   🔗 Heatmap de correlaciones...")
            fig3 = grafico_correlaciones(df)
            figuras.append(fig3)
            if guardar_html:
                fig3.write_html("correlaciones.html")
    except Exception as e:
        print(f"   ⚠️ No se pudo generar correlaciones: {e}")

    try:
        # 4. Radar de hábitos
        print("   🎯 Radar de hábitos...")
        fig4 = grafico_radar_habitos(df)
        figuras.append(fig4)
        if guardar_html:
            fig4.write_html("radar.html")
    except Exception as e:
        print(f"   ⚠️ No se pudo generar radar: {e}")

    try:
        # 5. Comparativa temporal (para la primera columna numérica)
        if len(columnas_numericas) > 0:
            print("   📅 Comparativa semanal...")
            fig5 = grafico_comparativa_temporal(df, columnas_numericas[0])
            figuras.append(fig5)
            if guardar_html:
                fig5.write_html("comparativa.html")
    except Exception as e:
        print(f"   ⚠️ No se pudo generar comparativa: {e}")

    print(f"✅ Se generaron {len(figuras)} visualizaciones")

    return figuras


