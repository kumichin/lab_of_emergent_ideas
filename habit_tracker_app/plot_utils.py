# GRÁFICO 3: HEATMAP DE CORRELACIONES
# =============================================================================

def grafico_correlaciones(df: pd.DataFrame) -> go.Figure:
    """
    Genera un heatmap de correlaciones entre todos los hábitos.

    Args:
        df: DataFrame con datos de hábitos

    Returns:
        Figura de Plotly con el heatmap
    """
    df_numerico = df.select_dtypes(include=[np.number])

    if len(df_numerico.columns) < 2:
        raise ValueError("Se necesitan al menos 2 columnas numéricas para calcular correlaciones")

    # Calcular matriz de correlación
    corr_matrix = df_numerico.corr()

    # Crear heatmap
    fig = go.Figure(data=go.Heatmap(
        z=corr_matrix.values,
        x=[col.replace('_', ' ').title() for col in corr_matrix.columns],
        y=[col.replace('_', ' ').title() for col in corr_matrix.columns],
        colorscale='RdBu',
        zmid=0,
        text=corr_matrix.values.round(2),
        texttemplate='%{text}',
        textfont={"size": 10},
        colorbar=dict(title="Correlación"),
        hovertemplate='%{x} vs %{y}<br>Correlación: %{z:.2f}<extra></extra>'
    ))

    fig.update_layout(
        title="🔗 Mapa de Correlaciones entre Hábitos",
        height=600,
        template=TEMPLATE,
        xaxis={'side': 'bottom'},
        yaxis={'side': 'left'}
    )

    return fig


