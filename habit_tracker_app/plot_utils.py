# GRÁFICO 5: RADAR CHART (RESUMEN GLOBAL)
# =============================================================================

def grafico_radar_habitos(df: pd.DataFrame, normalizar: bool = True) -> go.Figure:
    """
    Genera un gráfico de radar con el promedio de todos los hábitos.
    Útil para ver de un vistazo qué áreas están mejor/peor.

    Args:
        df: DataFrame con datos de hábitos
        normalizar: Si True, normaliza los valores entre 0-100

    Returns:
        Figura de Plotly con el radar chart
    """
    df_numerico = df.select_dtypes(include=[np.number])

    # Calcular promedios
    promedios = df_numerico.mean()

    if normalizar:
        # Normalizar a escala 0-100
        valores = ((promedios - promedios.min()) / (promedios.max() - promedios.min()) * 100).values
    else:
        valores = promedios.values

    categorias = [col.replace('_', ' ').title() for col in promedios.index]

    fig = go.Figure()

    fig.add_trace(go.Scatterpolar(
        r=valores,
        theta=categorias,
        fill='toself',
        name='Promedio',
        line_color=COLORES_NEUTROS[0],
        fillcolor=COLORES_NEUTROS[0],
        opacity=0.6,
        hovertemplate='<b>%{theta}</b><br>Valor: %{r:.1f}<extra></extra>'
    ))

    fig.update_layout(
        polar=dict(
            radialaxis=dict(
                visible=True,
                range=[0, 100] if normalizar else [0, max(valores) * 1.1]
            )
        ),
        title="🎯 Radar de Hábitos (Promedio General)",
        template=TEMPLATE,
        height=500
    )

    return fig


