# GRÁFICO 6: CALENDARIO DE CALOR (HEATMAP TEMPORAL)
# =============================================================================

def grafico_calendario(df: pd.DataFrame, columna: str) -> go.Figure:
    """
    Genera un calendario de calor mostrando el valor de un hábito cada día.
    Similar al contribution graph de GitHub.

    Args:
        df: DataFrame con datos de hábitos
        columna: Columna a visualizar

    Returns:
        Figura de Plotly con el calendario
    """
    col_fecha = _detectar_columna_fecha(df)

    if col_fecha is None:
        raise ValueError("No se encontró una columna de fecha")

    df_temp = df.copy()
    df_temp[col_fecha] = pd.to_datetime(df_temp[col_fecha])

    # Añadir información de día de la semana y semana del año
    df_temp['dia_semana'] = df_temp[col_fecha].dt.dayofweek
    df_temp['semana'] = df_temp[col_fecha].dt.isocalendar().week

    # Crear matriz para el heatmap
    pivot = df_temp.pivot_table(
        values=columna,
        index='dia_semana',
        columns='semana',
        aggfunc='mean'
    )

    dias = ['Lun', 'Mar', 'Mié', 'Jue', 'Vie', 'Sáb', 'Dom']

    tipo = _detectar_tipo_habito(columna)

    if tipo == 'positivo':
        colorscale = 'Greens'
    elif tipo == 'negativo':
        colorscale = 'Reds'
    else:
        colorscale = 'Blues'

    fig = go.Figure(data=go.Heatmap(
        z=pivot.values,
        x=pivot.columns,
        y=dias,
        colorscale=colorscale,
        hovertemplate='Semana %{x}<br>%{y}<br>Valor: %{z:.1f}<extra></extra>',
        colorbar=dict(title="Valor")
    ))

    fig.update_layout(
        title=f"📆 Calendario de {columna.replace('_', ' ').title()}",
        xaxis_title="Semana del año",
        yaxis_title="Día de la semana",
        template=TEMPLATE,
        height=400
    )

    return fig


