# =============================================================================
# CONFIGURACIÓN DE COLORES Y ESTILOS
# =============================================================================

COLORES_POSITIVOS = ['#10b981', '#34d399', '#6ee7b7']  # Verdes
COLORES_NEGATIVOS = ['#ef4444', '#f87171', '#fca5a5']  # Rojos
COLORES_NEUTROS = ['#3b82f6', '#60a5fa', '#93c5fd']    # Azules
COLORES_ADVERTENCIA = ['#f59e0b', '#fbbf24', '#fcd34d'] # Amarillos

TEMPLATE = 'plotly_white'  # Tema limpio y profesional


# =============================================================================
# DETECCIÓN AUTOMÁTICA DE COLUMNA DE FECHA
# =============================================================================

def _detectar_columna_fecha(df: pd.DataFrame) -> Optional[str]:
    """Detecta automáticamente la columna de fecha en el DataFrame."""
    for col in df.columns:
        if pd.api.types.is_datetime64_any_dtype(df[col]):
            return col
        # Intentar detectar por nombre
        if any(keyword in col.lower() for keyword in ['fecha', 'date', 'dia', 'day', 'timestamp']):
            return col
    return None


def _detectar_tipo_habito(nombre_col: str) -> str:
    """
    Clasifica el hábito para asignar colores apropiados.
    Returns: 'positivo', 'negativo', 'neutro'
    """
    nombre_lower = nombre_col.lower()

    # Hábitos positivos (más es mejor)
    positivos = ['ejercicio', 'exercise', 'pasos', 'steps', 'agua', 'water',
                 'sueño', 'sleep', 'productividad', 'productivity']

    # Hábitos negativos (menos es mejor)
    negativos = ['cigarrillos', 'cigarettes', 'alcohol', 'pantalla', 'screen',
                 'procrastinacion', 'procrastination', 'estres', 'stress']

    if any(palabra in nombre_lower for palabra in positivos):
        return 'positivo'
    elif any(palabra in nombre_lower for palabra in negativos):
        return 'negativo'
    else:
        return 'neutro'


