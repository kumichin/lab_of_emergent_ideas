# GRÁFICO 2: DISTRIBUCIONES (HISTOGRAMAS + BOX PLOTS)
# =============================================================================

def grafico_distribuciones(df: pd.DataFrame, columnas: Optional[List[str]] = None) -> go.Figure:
    """
    Genera histogramas y box plots para ver la distribución de cada hábito.

    Args:
        df: DataFrame con datos de hábitos
        columnas: Lista de columnas a graficar. Si None, usa todas las numéricas

    Returns:
        Figura de Plotly con las distribuciones
    """
    if columnas is None:
        columnas = df.select_dtypes(include=[np.number]).columns.tolist()

    # Crear subplots: una fila por columna, 2 columnas (histograma + boxplot)
    fig = make_subplots(
        rows=len(columnas),
        cols=2,
        subplot_titles=[item for col in columnas for item in [f'Distribución: {col}', f'Box Plot: {col}']],
        column_widths=[0.7, 0.3],
        vertical_spacing=0.08,
        horizontal_spacing=0.1
    )

    for i, col in enumerate(columnas, 1):
        tipo = _detectar_tipo_habito(col)

        if tipo == 'positivo':
            color = COLORES_POSITIVOS[0]
        elif tipo == 'negativo':
            color = COLORES_NEGATIVOS[0]
        else:
            color = COLORES_NEUTROS[0]

        # Histograma
        fig.add_trace(
            go.Histogram(
                x=df[col],
                name=col,
                marker_color=color,
                opacity=0.7,
                showlegend=False,
                hovertemplate='Rango: %{x}<br>Frecuencia: %{y}<extra></extra>'
            ),
            row=i, col=1
        )

        # Box plot
        fig.add_trace(
            go.Box(
                y=df[col],
                name=col,
                marker_color=color,
                showlegend=False,
                boxmean='sd',  # Mostrar media y desviación estándar
                hovertemplate='<b>Estadísticas</b><br>Valor: %{y:.1f}<extra></extra>'
            ),
            row=i, col=2
        )

    fig.update_layout(
        height=250 * len(columnas),
        title_text="📊 Distribución de Hábitos",
        template=TEMPLATE
    )

    return fig


