def cargar_y_limpiar_datos(ruta: str, estrategia_imputacion: str = 'auto') -> pd.DataFrame:
    """
    Función principal que carga un archivo y aplica limpieza optimizada para hábitos diarios.

    Args:
        ruta: Ruta del archivo (.csv, .xlsx, .xls, .docx)
        estrategia_imputacion:
            - 'auto' (RECOMENDADO): Detecta automáticamente la mejor estrategia por columna
            - 'zero': NaN = 0 para numéricos, 'No registrado' para categóricos
            - 'mean': NaN = media/moda (imputación estadística)
            - 'forward_fill': Propagar último valor válido
            - 'drop': Eliminar filas con NaN

    Returns:
        DataFrame limpio y listo para análisis

    Ejemplo:
        >>> df = cargar_y_limpiar_datos('habitos.csv')  # Usa 'auto' por defecto
        >>> df = cargar_y_limpiar_datos('habitos.xlsx', estrategia_imputacion='zero')
    """
    ruta_original = ruta
    ruta = ruta.lower()

    try:
        # ==================== PASO 1: CARGA ====================
        if ruta.endswith(('.csv', '.txt')):
            df = _cargar_csv(ruta_original)
        elif ruta.endswith(('.xlsx', '.xls')):
            df = _cargar_excel(ruta_original)
        elif ruta.endswith('.docx'):
            df = _cargar_word(ruta_original)
        else:
            raise ValueError("Formato de archivo no soportado. Por favor, usa .csv, .xlsx, .xls o .docx.")

        print(f"✅ Archivo '{ruta_original.split('/')[-1]}' cargado correctamente (Filas: {len(df)}, Columnas: {len(df.columns)})")

        # ==================== PASO 2: VALIDACIÓN ====================
        _validar_estructura_habitos(df)

        # ==================== PASO 3: LIMPIEZA E IMPUTACIÓN ====================
        df_limpio = imputacion_inteligente(df, estrategia_global=estrategia_imputacion)

        print(f"✨ Datos limpiados con estrategia '{estrategia_imputacion}'. Columnas restantes: {len(df_limpio.columns)}")

        # ==================== PASO 4: ORDENAMIENTO Y POST-PROCESAMIENTO ====================
        df_limpio = _ordenar_por_fecha(df_limpio)

        print(f"🎯 DataFrame listo para análisis. Forma final: {df_limpio.shape}")

        return df_limpio

    except Exception as e:
        print(f"❌ ERROR FATAL en el proceso de ingesta/limpieza: {e}")
        raise  # Propagamos el error en lugar de retornar DataFrame vacío


