# FUNCIONES DE CARGA DE ARCHIVOS
# =============================================================================

def _cargar_csv(ruta: str) -> pd.DataFrame:
    """Función auxiliar para cargar archivos CSV con detección automática de delimitadores."""
    try:
        # Intento 1: Motor rápido de C (coma como separador por defecto)
        return pd.read_csv(ruta, encoding='utf-8')
    except (pd.errors.ParserError, UnicodeDecodeError):
        try:
            # Intento 2: Detección automática de delimitadores (más lento pero robusto)
            return pd.read_csv(ruta, encoding='utf-8', sep=None, engine='python')
        except Exception:
            # Intento 3: Encoding alternativo (común en Windows)
            return pd.read_csv(ruta, encoding='latin-1', sep=None, engine='python')


def _cargar_excel(ruta: str) -> pd.DataFrame:
    """Función auxiliar para cargar archivos XLSX/XLS."""
    return pd.read_excel(ruta)


def _cargar_word(ruta: str) -> pd.DataFrame:
    """
    Función auxiliar para cargar la primera tabla de un archivo DOCX como DataFrame.
    Maneja robustamente la ausencia y el vacío de encabezados.
    """
    try:
        document = Document(ruta)
    except NameError:
        raise ImportError("La librería 'python-docx' no está disponible.")
    except Exception as e:
        raise IOError(f"Error al abrir el archivo Word: {e}")

    if not document.tables:
        raise ValueError(f"El archivo DOCX '{ruta.split('/')[-1]}' no contiene tablas.")

    tabla = document.tables[0]
    keys = [cell.text.strip() for cell in tabla.rows[0].cells]
    keys = [f'Columna_{i}' if not key else key for i, key in enumerate(keys)]
    data = [[cell.text.strip() for cell in row.cells] for row in tabla.rows[1:]]

    return pd.DataFrame(data, columns=keys)


