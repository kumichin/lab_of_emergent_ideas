# IMPUTACIÓN INTELIGENTE CON ESTRATEGIAS
# =============================================================================

def imputacion_inteligente(df: pd.DataFrame, estrategia_global: str = 'auto') -> pd.DataFrame:
    """
    Maneja NaNs de forma inteligente según el tipo de columna.

    Args:
        df: DataFrame de entrada
        estrategia_global:
            - 'auto' (RECOMENDADO): Aplica la mejor estrategia según el tipo de columna
            - 'zero': Rellena todo con 0 (numéricos) o 'No registrado' (categóricos)
            - 'mean': Rellena con media/moda (tu código original)
            - 'forward_fill': Propaga el último valor válido
            - 'drop': Elimina filas con NaN

    Returns:
        DataFrame limpio
    """
    df_limpio = df.copy()

    # 1. Convertir tipos de forma inteligente
    df_limpio = _convertir_tipos_inteligente(df_limpio)

    # 2. Aplicar estrategia
    if estrategia_global == 'auto':
        # 🔥 MODO AUTOMÁTICO: La mejor opción para hábitos diarios
        for col in df_limpio.columns:
            tipo = _detectar_tipo_columna(df_limpio, col)

            if tipo == 'fecha':
                # Las fechas no se imputan, se mantienen como NaT si faltan
                pass

            elif tipo == 'numerica_habito':
                # Hábitos cuantificables: NaN = no se realizó la actividad
                df_limpio[col] = df_limpio[col].fillna(0)

            elif tipo == 'numerica_metrica':
                # Métricas continuas: propagar el último valor válido
                df_limpio[col].fillna(method='ffill', inplace=True)

            elif tipo == 'categorica':
                # Categóricas: rellenar con 'No registrado'
                df_limpio[col].fillna('No registrado', inplace=True)

    elif estrategia_global == 'zero':
        columnas_numericas = df_limpio.select_dtypes(include=[np.number]).columns
        df_limpio[columnas_numericas] = df_limpio[columnas_numericas].fillna(0)

        columnas_categoricas = df_limpio.select_dtypes(include=['object']).columns
        for col in columnas_categoricas:
            df_limpio[col].fillna('No registrado', inplace=True)

    elif estrategia_global == 'mean':
        # Tu código original
        columnas_numericas = df_limpio.select_dtypes(include=[np.number]).columns
        medias_validas = df_limpio[columnas_numericas].mean().dropna()
        df_limpio[columnas_numericas] = df_limpio[columnas_numericas].fillna(medias_validas)

        columnas_categoricas = df_limpio.select_dtypes(include=['object']).columns
        for col in columnas_categoricas:
            moda_serie = df_limpio[col].mode()
            if not moda_serie.empty:
                df_limpio[col].fillna(moda_serie.iloc[0], inplace=True)

    elif estrategia_global == 'forward_fill':
        df_limpio = df_limpio.fillna(method='ffill')

    elif estrategia_global == 'drop':
        df_limpio = df_limpio.dropna()

    else:
        raise ValueError(f"Estrategia '{estrategia_global}' no válida. Usa: 'auto', 'zero', 'mean', 'forward_fill', 'drop'")

    # 3. Eliminar columnas 100% vacías
    df_limpio.dropna(axis=1, how='all', inplace=True)

    return df_limpio


