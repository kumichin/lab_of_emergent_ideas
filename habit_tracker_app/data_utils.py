def _validar_estructura_habitos(df: pd.DataFrame) -> None:
    """
    Valida que el DataFrame tenga una estructura válida para análisis de hábitos.
    Lanza advertencias si falta información crítica.
    """
    # Buscar columna de fecha
    columnas_fecha = [col for col in df.columns if _detectar_tipo_columna(df, col) == 'fecha']

    if not columnas_fecha:
        print("⚠️  ADVERTENCIA: No se detectó una columna de fecha. Considera añadir 'Fecha' para análisis temporal.")
    else:
        print(f"✅ Columna de fecha detectada: '{columnas_fecha[0]}'")

    # Verificar si hay suficientes filas para análisis
    if len(df) < 7:
        print(f"⚠️  ADVERTENCIA: Solo hay {len(df)} filas. Se recomienda al menos 7 días para análisis significativos.")


def _ordenar_por_fecha(df: pd.DataFrame) -> pd.DataFrame:
    """
    Ordena el DataFrame por fecha si existe una columna de fecha.
    También elimina duplicados de fecha manteniendo el registro más reciente.
    """
    df_ordenado = df.copy()

    # Buscar columna de fecha
    columnas_fecha = [col for col in df_ordenado.columns if _detectar_tipo_columna(df_ordenado, col) == 'fecha']

    if columnas_fecha:
        col_fecha = columnas_fecha[0]

        # Eliminar duplicados por fecha (mantener el último registro)
        duplicados_antes = len(df_ordenado)
        df_ordenado = df_ordenado.drop_duplicates(subset=[col_fecha], keep='last')
        duplicados_despues = len(df_ordenado)

        if duplicados_antes != duplicados_despues:
            print(f"🔄 Se eliminaron {duplicados_antes - duplicados_despues} registros duplicados por fecha.")

        # Ordenar por fecha
        df_ordenado = df_ordenado.sort_values(by=col_fecha).reset_index(drop=True)
        print(f"📅 Datos ordenados por fecha ({col_fecha})")

    return df_ordenado


