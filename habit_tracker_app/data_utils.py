def _detectar_tipo_columna(df: pd.DataFrame, col: str) -> str:
    """
    Detecta inteligentemente el tipo de columna para aplicar la estrategia correcta.

    Returns:
        'fecha', 'numerica_habito', 'numerica_metrica', 'categorica'
    """
    col_lower = col.lower()

    # 1. Detectar columnas de fecha
    if any(keyword in col_lower for keyword in ['fecha', 'date', 'dia', 'day', 'timestamp']):
        return 'fecha'

    # 2. Detectar hábitos cuantificables (NaN debería ser 0)
    habitos_zero = [
        'ejercicio', 'pasos', 'steps', 'agua', 'water', 'calorias', 'calories',
        'horas', 'hours', 'minutos', 'minutes', 'vasos', 'glasses', 'km',
        'repeticiones', 'reps', 'series', 'sets', 'cigarrillos', 'cigarettes'
    ]
    if any(keyword in col_lower for keyword in habitos_zero):
        return 'numerica_habito'

    # 3. Detectar métricas continuas (NaN debería propagarse del valor anterior)
    metricas_continuas = [
        'peso', 'weight', 'masa', 'altura', 'height', 'imc', 'bmi',
        'temperatura', 'temp', 'presion', 'pressure', 'glucosa', 'glucose'
    ]
    if any(keyword in col_lower for keyword in metricas_continuas):
        return 'numerica_metrica'

    # 4. Por defecto, categórica
    return 'categorica'


def _convertir_tipos_inteligente(df: pd.DataFrame) -> pd.DataFrame:
    """
    Convierte tipos de datos de forma inteligente sin convertir TODO a numérico.

    Solo convierte columnas que realmente parecen numéricas.
    """
    df_convertido = df.copy()

    for col in df_convertido.columns:
        tipo = _detectar_tipo_columna(df_convertido, col)

        if tipo == 'fecha':
            # Convertir a datetime
            df_convertido[col] = pd.to_datetime(df_convertido[col], errors='coerce')

        elif tipo in ['numerica_habito', 'numerica_metrica']:
            # Convertir a numérico
            df_convertido[col] = pd.to_numeric(df_convertido[col], errors='coerce')

        # Las categóricas se mantienen como object (no hacemos nada)

    return df_convertido


